import type { Fixture } from '@/models/fixture';
import type { FixtureId } from '@/models/common';
import type { PatchItem } from '@/models/patch';

/**
 * Offline patch export for consoles. A PWA can't reliably open a socket to a
 * desk on the lighting network, so instead we hand the operator files and
 * text they can bring to the console: a universal CSV, a grandMA3 address
 * macro, and a printable sheet.
 */

export interface ExportRow {
  fid: number;
  fixtureId: FixtureId;
  label: string;
  manufacturer: string;
  model: string;
  mode: string;
  footprint: number;
  universe: number;
  address: number;
  /** Absolute DMX address across universes ((u-1)*512 + a). */
  absolute: number;
}

/** Order the patch by universe/address and assign sequential fixture IDs. */
export function buildExportRows(
  patch: PatchItem[],
  fixtures: Map<FixtureId, Fixture>,
  startFid = 101,
): ExportRow[] {
  return [...patch]
    .sort((a, b) => a.universe - b.universe || a.startAddress - b.startAddress)
    .map((p, i) => {
      const fx = fixtures.get(p.fixtureId);
      return {
        fid: startFid + i,
        fixtureId: p.fixtureId,
        label: p.label,
        manufacturer: fx?.manufacturer ?? 'Unknown',
        model: fx?.model ?? p.fixtureId,
        mode: p.mode,
        footprint: p.footprint,
        universe: p.universe,
        address: p.startAddress,
        absolute: (p.universe - 1) * 512 + p.startAddress,
      };
    });
}

/** MA-style dotted address: universe.address (e.g. 3.123). */
export const dotted = (r: Pick<ExportRow, 'universe' | 'address'>): string => `${r.universe}.${r.address}`;

const csvCell = (v: string | number): string => {
  const s = String(v);
  // Quote anything with separators/quotes; neutralise spreadsheet formulas.
  const safe = /^[=+\-@]/.test(s) ? `'${s}` : s;
  return /[",\n]/.test(safe) ? `"${safe.replace(/"/g, '""')}"` : safe;
};

export function toCsv(rows: ExportRow[]): string {
  const header = ['FID', 'Label', 'Manufacturer', 'Model', 'Mode', 'Footprint', 'Universe', 'Address', 'Universe.Address', 'Absolute'];
  const lines = rows.map((r) =>
    [r.fid, r.label, r.manufacturer, r.model, r.mode, r.footprint, r.universe, r.address, dotted(r), r.absolute]
      .map(csvCell)
      .join(','),
  );
  return [header.join(','), ...lines].join('\r\n') + '\r\n';
}

/**
 * grandMA3 address macro. `Patch Fixture <FID> <universe>.<address>` assigns
 * the DMX address of a fixture that already exists in the show — so the
 * fixtures (types, modes, FIDs) are added in the Patch menu first, then this
 * runs every address in one go.
 */
export function toMa3Macro(rows: ExportRow[], showName: string): string {
  const head = [
    `// ${showName} — address macro generated by Shepley Lighting Companion`,
    `// 1. In Patch, add the fixtures below with these FIDs, types and modes.`,
    `// 2. Run these lines (paste into the command line, or a macro) to set every address.`,
    '',
  ];
  return [...head, ...rows.map((r) => `Patch Fixture ${r.fid} ${dotted(r)}`)].join('\n') + '\n';
}

/** Group rows into fixture-type blocks — how you'd add them in a console's patch. */
export function typeBlocks(rows: ExportRow[]): Array<{ key: string; manufacturer: string; model: string; mode: string; fids: number[] }> {
  const map = new Map<string, { key: string; manufacturer: string; model: string; mode: string; fids: number[] }>();
  for (const r of rows) {
    const key = `${r.manufacturer}|${r.model}|${r.mode}`;
    const block = map.get(key) ?? { key, manufacturer: r.manufacturer, model: r.model, mode: r.mode, fids: [] };
    block.fids.push(r.fid);
    map.set(key, block);
  }
  return [...map.values()];
}

/** Compact FID list, e.g. [101,102,103,107] → "101 Thru 103 + 107". */
export function fidRanges(fids: number[]): string {
  const sorted = [...fids].sort((a, b) => a - b);
  const parts: string[] = [];
  let start = sorted[0];
  let prev = sorted[0];
  for (let i = 1; i <= sorted.length; i++) {
    const n = sorted[i];
    if (n === prev! + 1) {
      prev = n;
      continue;
    }
    if (start !== undefined) parts.push(start === prev ? `${start}` : `${start} Thru ${prev}`);
    start = n;
    prev = n;
  }
  return parts.join(' + ');
}
